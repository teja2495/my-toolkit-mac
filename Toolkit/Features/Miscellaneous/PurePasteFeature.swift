import AppKit
import Carbon.HIToolbox
import Foundation

/// Watches the general pasteboard and, whenever a copy carries rich text (RTF, HTML, web archives),
/// replaces it with the plain-text version only. Fonts, sizes, and colors are dropped; the text itself,
/// including line breaks, spacing, tabs, and hyphen/bullet characters, is kept as-is, so it pastes in the
/// destination's own style. ⌥⌘C copies with all formatting kept.
@MainActor
final class PurePasteFeature: AppFeature {
    let id = "pure-paste"

    private var pollTimer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var keepFormattingHotKey: HotKey?
    /// Set by ⌥⌘C: the next clipboard change before this time is left untouched.
    private var keepFormattingUntil: Date?

    /// Pasteboard types that carry styling information.
    private static let richTypes: Set<NSPasteboard.PasteboardType> = [
        .rtf,
        .rtfd,
        .html,
        .init("com.apple.flat-rtfd"),
        .init("com.apple.webarchive"),
        .init("Apple Web Archive pasteboard type"),
        .init("NeXT Rich Text Format v1.0 pasteboard type"),
        .init("Apple HTML pasteboard type")
    ]

    /// Copies that should never be rewritten: sensitive or throwaway data, and file copies.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .fileURL
    ]

    func start() {
        guard pollTimer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount

        let timer = Timer(timeInterval: 0.25, repeats: true) { _ in
            Task { @MainActor [weak self] in
                self?.pollPasteboard()
            }
        }
        timer.tolerance = 0.05
        RunLoop.main.add(timer, forMode: .common)
        pollTimer = timer

        keepFormattingHotKey = HotKey(
            carbonKeyCode: kVK_ANSI_C,
            carbonModifiers: cmdKey | optionKey,
            onKeyDown: { [weak self] in
                MainActor.assumeIsolated {
                    self?.copyKeepingFormatting()
                }
            },
            onKeyUp: {}
        )
    }

    func stop() {
        pollTimer?.invalidate()
        pollTimer = nil
        keepFormattingHotKey = nil
        keepFormattingUntil = nil
    }

    /// ⌥⌘C: sends a normal ⌘C to the frontmost app and leaves the resulting copy formatted.
    private func copyKeepingFormatting() {
        guard AXIsProcessTrusted() else { return }
        keepFormattingUntil = Date().addingTimeInterval(2)

        let source = CGEventSource(stateID: .combinedSessionState)
        let cKey = CGKeyCode(kVK_ANSI_C)
        let down = CGEvent(keyboardEventSource: source, virtualKey: cKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: cKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    private func pollPasteboard() {
        let pasteboard = NSPasteboard.general
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        if let keepFormattingUntil {
            self.keepFormattingUntil = nil
            if Date() < keepFormattingUntil { return }
        }

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes),
              !types.isDisjoint(with: Self.richTypes),
              let plainText = pasteboard.string(forType: .string),
              !plainText.isEmpty
        else { return }

        let text = Self.listAwareText(from: pasteboard, types: types, fallback: plainText)

        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
    }

    // MARK: - Lists

    private static let maxHTMLBytes = 512 * 1024
    private static let bulletCharacters = "•◦▪▫‣⁃●○■□◆◇➢➤►▸·∙"
    /// A leading list marker as rendered into text by AppKit, e.g. "\t•\t", "\t1.\t", "\ta)\t".
    private static let markerPattern = try! NSRegularExpression(
        pattern: "^[\\t ]*(?:[\(bulletCharacters)\\-–—*]|[0-9]+[.)]?|[a-zA-Z][.)]?|[ivxlcdmIVXLCDM]+[.)]?)[\\t ]+"
    )
    private static let bulletLinePattern = try! NSRegularExpression(
        pattern: "^([\\t ]*)[\(bulletCharacters)][\\t ]+",
        options: [.anchorsMatchLines]
    )

    /// Rebuilds the text from the rich representation so list items come out as "- item"
    /// (ordered lists keep their numbers, nested items are indented). Falls back to the plain text.
    private static func listAwareText(
        from pasteboard: NSPasteboard,
        types: Set<NSPasteboard.PasteboardType>,
        fallback: String
    ) -> String {
        guard let attributed = attributedString(from: pasteboard, types: types),
              let rebuilt = rebuildLists(in: attributed)
        else {
            return replacingBulletCharacters(in: fallback)
        }

        // HTML/RTF import usually appends a trailing newline the source didn't copy.
        var result = rebuilt
        if !fallback.hasSuffix("\n") {
            while result.hasSuffix("\n") { result.removeLast() }
        }
        return result
    }

    private static func attributedString(
        from pasteboard: NSPasteboard,
        types: Set<NSPasteboard.PasteboardType>
    ) -> NSAttributedString? {
        if types.contains(.rtf), let data = pasteboard.data(forType: .rtf),
           let attributed = NSAttributedString(rtf: data, documentAttributes: nil) {
            return attributed
        }
        if types.contains(.rtfd), let data = pasteboard.data(forType: .rtfd),
           let attributed = NSAttributedString(rtfd: data, documentAttributes: nil) {
            return attributed
        }
        // HTML import goes through WebKit, so only use it when there's actually a list to recover.
        if types.contains(.html), let data = pasteboard.data(forType: .html),
           data.count <= maxHTMLBytes,
           let html = String(data: data, encoding: .utf8),
           html.range(of: "<li", options: .caseInsensitive) != nil,
           let attributed = try? NSAttributedString(
               data: Data(html.utf8),
               options: [
                   .documentType: NSAttributedString.DocumentType.html,
                   .characterEncoding: String.Encoding.utf8.rawValue
               ],
               documentAttributes: nil
           ) {
            return attributed
        }
        return nil
    }

    /// Returns nil when the text has no lists, so the source app's own plain text is kept.
    private static func rebuildLists(in attributed: NSAttributedString) -> String? {
        let string = attributed.string as NSString
        var lines: [String] = []
        var foundList = false
        var location = 0

        while location < string.length {
            var start = 0, end = 0, contentsEnd = 0
            string.getParagraphStart(&start, end: &end, contentsEnd: &contentsEnd, for: NSRange(location: location, length: 0))
            let paragraphRange = NSRange(location: start, length: contentsEnd - start)
            let line = string.substring(with: paragraphRange)
            let separator = string.substring(with: NSRange(location: contentsEnd, length: end - contentsEnd))
            location = end

            let style = paragraphRange.length > 0
                ? attributed.attribute(.paragraphStyle, at: paragraphRange.location, effectiveRange: nil) as? NSParagraphStyle
                : nil
            guard let lists = style?.textLists, let list = lists.last, !line.isEmpty else {
                lines.append(line + separator)
                continue
            }

            foundList = true
            let indent = String(repeating: "  ", count: max(0, lists.count - 1))
            let range = NSRange(location: 0, length: (line as NSString).length)
            let marker = markerPattern.firstMatch(in: line, range: range)
            let markerText = marker.map { (line as NSString).substring(with: $0.range) } ?? ""
            let body = marker.map { (line as NSString).substring(from: $0.range.upperBound) } ?? line

            let prefix: String
            if list.isOrdered, let number = markerText.trimmingCharacters(in: .whitespacesAndNewlines).nilIfEmpty {
                let punctuated = number.hasSuffix(".") || number.hasSuffix(")") ? number : number + "."
                prefix = punctuated + " "
            } else {
                prefix = "- "
            }
            lines.append(indent + prefix + body + separator)
        }

        return foundList ? lines.joined() : nil
    }

    /// For copies without list structure, still turn literal bullet characters at line starts into hyphens.
    private static func replacingBulletCharacters(in text: String) -> String {
        bulletLinePattern.stringByReplacingMatches(
            in: text,
            range: NSRange(location: 0, length: (text as NSString).length),
            withTemplate: "$1- "
        )
    }
}

private extension NSTextList {
    var isOrdered: Bool {
        switch markerFormat {
        case .disc, .circle, .square, .diamond, .hyphen, .box, .check:
            return false
        default:
            return true
        }
    }
}

private extension String {
    var nilIfEmpty: String? { isEmpty ? nil : self }
}
