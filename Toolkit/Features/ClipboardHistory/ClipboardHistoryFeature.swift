import AppKit
import Carbon.HIToolbox
import Foundation

@MainActor
final class ClipboardHistoryFeature: AppFeature {
    let id = "clipboard-history"

    let store = ClipboardHistoryStore()
    private lazy var panelController = ClipboardHistoryPanelController(store: store) { [weak self] items in
        self?.writeToPasteboard(items)
    }

    private var pollTimer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var isStarted = false
    private var triggerHotKey: HotKey?

    /// Hard-coded trigger: ⌥V.
    static let triggerSymbol = "⌥ V"

    /// Pasteboard types that password managers and similar apps use to mark sensitive or throwaway data.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword")
    ]

    func start() {
        guard !isStarted else { return }
        isStarted = true
        lastChangeCount = NSPasteboard.general.changeCount

        let timer = Timer(timeInterval: 0.5, repeats: true) { _ in
            Task { @MainActor [weak self] in
                self?.pollPasteboard()
            }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        pollTimer = timer

        triggerHotKey = HotKey(
            carbonKeyCode: kVK_ANSI_V,
            carbonModifiers: optionKey,
            onKeyDown: { [weak self] in
                MainActor.assumeIsolated {
                    self?.panelController.toggle()
                }
            },
            onKeyUp: {}
        )
    }

    func stop() {
        guard isStarted else { return }
        isStarted = false
        pollTimer?.invalidate()
        pollTimer = nil
        triggerHotKey = nil
        panelController.close()
    }

    func showPanel() {
        panelController.show()
    }

    private func pollPasteboard() {
        let pasteboard = NSPasteboard.general
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        // Skip file copies from Finder; they only carry a file icon image and a path.
        guard !types.contains(.fileURL) else { return }

        let sourceApp = NSWorkspace.shared.frontmostApplication
        guard !Self.isExcluded(sourceApp) else { return }
        let sourceAppName = sourceApp?.localizedName

        if let text = pasteboard.string(forType: .string) {
            store.addText(text, sourceAppName: sourceAppName)
            return
        }

        if let image = NSImage(pasteboard: pasteboard),
           let (pngData, pixelSize) = Self.pngData(from: image) {
            store.addImage(pngData: pngData, size: pixelSize, sourceAppName: sourceAppName)
        }
    }

    /// Apps whose copies are never saved (password managers).
    private static func isExcluded(_ app: NSRunningApplication?) -> Bool {
        guard let app else { return false }
        let bundleID = app.bundleIdentifier?.lowercased() ?? ""
        let name = app.localizedName?.lowercased() ?? ""
        return bundleID.contains("enpass") || name.contains("enpass")
    }

    /// Multiple items are joined as text separated by a blank line; images are skipped in that case.
    private func writeToPasteboard(_ items: [ClipboardHistoryItem]) {
        let textItems = items.filter { $0.kind == .text }
        guard items.count > 1, !textItems.isEmpty else {
            if let item = items.first { writeToPasteboard(item) }
            return
        }
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(textItems.map { $0.text ?? "" }.joined(separator: "\n\n"), forType: .string)
        lastChangeCount = pasteboard.changeCount
    }

    private func writeToPasteboard(_ item: ClipboardHistoryItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            guard let url = store.imageURL(for: item), let data = try? Data(contentsOf: url) else { return }
            pasteboard.setData(data, forType: .png)
            if let tiff = NSImage(data: data)?.tiffRepresentation {
                pasteboard.setData(tiff, forType: .tiff)
            }
        }
        lastChangeCount = pasteboard.changeCount
        store.promote(id: item.id)
    }

    private static func pngData(from image: NSImage) -> (Data, CGSize)? {
        guard let tiff = image.tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:]) else {
            return nil
        }
        return (png, CGSize(width: rep.pixelsWide, height: rep.pixelsHigh))
    }
}
